export const referenceLocales = Object.freeze(Object.keys(referenceCopy))
export function resolveReferenceLocale({ search = '', cookie = '', languages = [] } = {}) {
 const normalize = value => { const tag = String(value ?? '').toLowerCase(); if (tag === 'zh-cn' || tag === 'zh-sg' || tag.startsWith('zh-hans')) return 'zh-CN'; const primary = tag.split('-')[0]; return ['en','ja','zh'].includes(primary) ? primary : undefined }
 const query = new URLSearchParams(search).get('locale')
 const stored = cookie.split(';').map(part => part.trim()).find(part => part.startsWith('locale='))?.slice(7)
 for (const value of [query,stored,...languages]) { const locale = normalize(value); if (locale) return locale }
 return 'en'
}
export function referenceText(locale, key, values = {}) {
 const template = referenceCopy[locale]?.[key]
 if (typeof template !== 'string') throw new Error('Unknown reference copy key')
 return template.replace(/\{(\w+)\}/g, (_match, name) => String(values[name] ?? ''))
}
