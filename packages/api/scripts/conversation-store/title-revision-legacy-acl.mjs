// [COMP:api/migration-owner-role] Exact historical title ACL prerequisite.
import { createHash } from 'node:crypto'
import { readFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { executableProjection } from './executable-record.mjs'
import { currentInstallationAuthenticationSource } from './installation-authentication-8281.mjs'
import { admissionPredecessorSql, admissionSignature, predecessorAdmissionSha } from './title-revision-admission.mjs'

export const migrationName = '82860_legacy_title_admission_privilege_order.sql'
const titleMigration = '8286_title_revision_admission.sql'
const sourceRoot = fileURLToPath(new URL('../../', import.meta.url))
const quote = value => "'" + value.replaceAll("'", "''") + "'"
const sha = bytes => createHash('sha256').update(bytes).digest('hex')

async function reviewedFile(path, digest) {
  const bytes = await readFile(new URL(`../../${path}`, import.meta.url))
  if (sha(bytes) !== digest) throw new Error(`title_acl_prerequisite_source_changed: ${path}`)
  return bytes.toString('utf8')
}

function replaceOnce(source, before, after) {
  if (source.split(before).length !== 2) throw new Error('title_acl_prerequisite_rewrite_changed')
  return source.replace(before, () => after)
}

function section(source, first, after) {
  const start = source.indexOf(first)
  const end = source.indexOf(after, start + first.length)
  if (start < 0 || end < 0) throw new Error('title_acl_prerequisite_section_changed')
  return source.slice(start, end).trim()
}

function execute(tag, sql) {
  const delimiter = `$title_acl_${tag}$`
  if (sql.includes(delimiter)) throw new Error('title_acl_prerequisite_delimiter_changed')
  return `EXECUTE ${delimiter}\n${sql}\n${delimiter};`
}

export async function buildTitleRevisionLegacyAclSql() {
  const titleSql = await reviewedFile(`migrations/${titleMigration}`, 'c601a5145d310b8381c69b88958f8c1f54215805d2c95761ff5ad09afae9c2f7')
  const successorBody = await reviewedFile('scripts/conversation-store/title-revision-admission.sql', '8a7998238021eaa05c7aa4a8f8a8f59d5e9c812cc94e4ffbe1a854f433f31162')
  await reviewedFile('scripts/conversation-store/title-revision-admission.mjs', '9fe8777ee3dc44c15dfd699a55ba5072eefb3916b49f0ada8fe40788611ffbcc')
  await reviewedFile('scripts/conversation-store/installation-authentication-8281.mjs', 'b664d546437d2bb09b64773f0270deacadbc7b2c20393e4dce192829071d275f')
  const { sql: authenticate, cleanup } = await currentInstallationAuthenticationSource({ sourceRoot })

  // Use the shipped 8286 dependency walk, with the one ACL member as its only root.
  const scope = replaceOnce(section(titleSql, 'CREATE TEMP TABLE c8286_affected_functions(', 'CREATE FUNCTION pg_temp.c8286_source_body('),
    `WHERE signature IN('native_turn_helpers_current()','native_turn_publication_contract()',${quote(admissionSignature)});`,
    `WHERE signature=${quote(admissionSignature)};`)
  // Re-render only the authenticated dependency closure with the unchanged 8281
  // renderer. The 8286 body successor is still installed by its own migration.
  const propagation = replaceOnce(replaceOnce(section(titleSql, 'DO $title_admission_propagate$', 'DO $title_admission_rendered$'),
    'FROM a8281_publication_successor_templates t ORDER BY',
    'FROM a8281_publication_successor_templates t JOIN c8286_affected_functions a USING(signature) ORDER BY'),
    'pg_temp.c8286_source_body(routine.signature,routine.parts,true)',
    'pg_temp.a8281_conversion_source_body(routine.signature,routine.parts,true)')
  const record = section(titleSql, 'DO $title_admission_record$', 'END $c8286_witness_relation$;') + '\nEND $c8286_witness_relation$;'

  return `-- [COMP:api/migration-owner-role] Historical title routine ACL prerequisite.
-- Generated by build-title-revision-legacy-acl.mjs. Applied SQL is immutable.
BEGIN;
DO $title_legacy_acl$
DECLARE routine pg_proc; repaired pg_proc; before_hash text; after_hash text; updated integer;
 owner_id oid:=(SELECT relowner FROM pg_class WHERE oid='public.sessions'::regclass);
 runtime_id oid:=(SELECT oid FROM pg_roles WHERE rolname='app_user');
 canonical_acl aclitem[]; legacy_acl aclitem[];
 routine_name constant text:=${quote(admissionSignature)};
 ignored_fields constant text[]:=ARRAY['oid','proname','pronamespace','proowner','proacl','prosrc'];
 expected_metadata jsonb:=jsonb_build_object(
  'probin',NULL,'procost',100,'prokind','f','prolang',(SELECT oid FROM pg_language WHERE lanname='plpgsql'),
  'prorows',0,'pronargs',2,'proconfig',ARRAY['search_path=pg_catalog, public, pg_temp'],
  'proretset',false,'prosecdef',true,'prorettype','boolean'::regtype::oid,'prosqlbody',NULL,
  'prosupport',0::regproc,'proargmodes',NULL,'proargnames',ARRAY['w','i'],
  'proargtypes',concat('uuid'::regtype::oid,' ','uuid'::regtype::oid)::oidvector,
  'proisstrict',false,'proparallel','u','protrftypes',NULL,'provariadic',0::oid,'provolatile','v',
  'proleakproof',false,'proallargtypes',NULL,'proargdefaults',NULL,'pronargdefaults',0);
BEGIN
 IF EXISTS(SELECT 1 FROM pg_event_trigger WHERE evtenabled<>'D')
 THEN RAISE EXCEPTION 'title_acl_prerequisite_unreviewed_ddl_trigger';END IF;
 SELECT * INTO routine FROM pg_proc WHERE oid=to_regprocedure('public.'||routine_name);
 IF routine.oid IS NULL OR routine.pronamespace<>'public'::regnamespace OR routine.proowner<>owner_id
  OR current_user::regrole::oid<>owner_id OR runtime_id IS NULL OR runtime_id=owner_id
 THEN RAISE EXCEPTION 'title_acl_prerequisite_identity_changed';END IF;

 IF to_jsonb(routine)-ignored_fields IS DISTINCT FROM expected_metadata
  OR NOT EXISTS(SELECT 1 FROM public.native_turn_contract_helpers h WHERE h.signature=routine_name
    AND ${executableProjection('routine')} IS NOT DISTINCT FROM h.contract)
 THEN RAISE EXCEPTION 'title_acl_prerequisite_contract_changed';END IF;

 canonical_acl:=ARRAY[makeaclitem(owner_id,owner_id,'EXECUTE',false),makeaclitem(runtime_id,owner_id,'EXECUTE',false)];
 legacy_acl:=ARRAY[canonical_acl[2],canonical_acl[1]];
 IF EXISTS(SELECT 1 FROM public._migrations WHERE name=${quote(titleMigration)}) THEN
  IF routine.proacl IS DISTINCT FROM canonical_acl OR (routine.prosrc COLLATE "C") IS DISTINCT FROM ${quote(successorBody)}
  THEN RAISE EXCEPTION 'title_acl_prerequisite_successor_changed';END IF;
  RETURN;
 END IF;
 IF encode(sha256(convert_to(routine.prosrc,'UTF8')),'hex')<>${quote(predecessorAdmissionSha)}
  OR NOT EXISTS(SELECT 1 FROM public._migrations WHERE name='8285_owner_forced_rls_retirement.sql')
 THEN RAISE EXCEPTION 'title_acl_prerequisite_predecessor_changed';END IF;
 IF routine.proacl IS NOT DISTINCT FROM canonical_acl THEN RETURN;END IF;
 IF routine.proacl IS DISTINCT FROM legacy_acl THEN RAISE EXCEPTION 'title_acl_prerequisite_acl_changed';END IF;

 LOCK TABLE public.native_turn_contract_helpers,public.native_retained_contract_helpers IN SHARE ROW EXCLUSIVE MODE;
 ${execute('authenticate', authenticate)}
 ${execute('scope', scope)}
 IF NOT EXISTS(SELECT 1 FROM pg_temp.c8286_affected_functions a
  WHERE a.signature='application_native_title_group_helpers_current()')
 THEN RAISE EXCEPTION 'title_acl_prerequisite_title_consumer_missing';END IF;
 before_hash:=encode(sha256(convert_to(to_jsonb(routine)::text,'UTF8')),'hex');
 IF NOT EXISTS(SELECT 1 FROM pg_temp.a8281_publication_expected_current e WHERE e.signature=routine_name
   AND e.metadata=to_jsonb(routine))
  OR EXISTS(SELECT 1 FROM public.native_retained_contract_helpers h WHERE h.signature=routine_name AND h.fingerprint<>before_hash)
 THEN RAISE EXCEPTION 'title_acl_prerequisite_registry_changed';END IF;

 REVOKE EXECUTE ON FUNCTION public.${admissionSignature} FROM app_user;
 GRANT EXECUTE ON FUNCTION public.${admissionSignature} TO app_user;
 SELECT * INTO STRICT repaired FROM pg_proc WHERE oid=routine.oid;
 IF to_jsonb(repaired)-'proacl' IS DISTINCT FROM to_jsonb(routine)-'proacl'
  OR repaired.proacl IS DISTINCT FROM canonical_acl
 THEN RAISE EXCEPTION 'title_acl_prerequisite_repair_changed';END IF;
 after_hash:=encode(sha256(convert_to(to_jsonb(repaired)::text,'UTF8')),'hex');
 UPDATE public.native_turn_contract_helpers h SET contract=${executableProjection('repaired')}
 WHERE h.signature=routine_name AND h.contract IS NOT DISTINCT FROM ${executableProjection('routine')};
 GET DIAGNOSTICS updated=ROW_COUNT;
 IF updated<>1 THEN RAISE EXCEPTION 'title_acl_prerequisite_registry_changed';END IF;
 UPDATE public.native_retained_contract_helpers h SET fingerprint=after_hash
 WHERE h.signature=routine_name AND h.fingerprint=before_hash;
 UPDATE pg_temp.a8281_publication_expected_current e SET metadata=to_jsonb(repaired) WHERE e.signature=routine_name;
 ${execute('propagate', propagation)}
 ${execute('check', admissionPredecessorSql)}
 ${execute('record', record)}
 ${execute('cleanup', cleanup)}
 DROP TABLE pg_temp.c8286_affected_functions;
END $title_legacy_acl$;
COMMIT;
`
}
