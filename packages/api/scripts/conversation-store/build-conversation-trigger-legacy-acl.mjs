// [COMP:api/migration-owner-role] Render exact historical Session trigger ACL repair.
import { createHash } from 'node:crypto'
import { readFile, readdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { historicalOrdinaryAclSql } from './conversation-ordinary-legacy-acl.mjs'

const directory = new URL('../../migrations/', import.meta.url)
const name = '82980_legacy_conversation_trigger_privileges.sql'
const source = '8297_conversation_record_admission.sql'
const successor = '8298_legacy_bypass_retirement.sql'
const successorDigest = 'e0dba38f73b1ebdefaeab8d9bf53b77f5a041451365faef872646444b909fefd'
const sourceDigest = 'c7dde30c0cefe61167be20492cb0df68a587c26352314e3dfab794ded77c4bf7'
const predecessorTriggers = [
  ['prevent_locked_session_context_change', 'sessions_context_immutable_after_lock', 19,
    ['context_group_id', 'context_project_id', 'context_compartments']],
  ['stamp_session_project_label', 'aaab_session_project_label', 23, ['context_project_id', 'visibility']],
  ['validate_session_context_binding', 'sessions_context_binding_valid', 23,
    ['workspace_id', 'context_group_id', 'context_project_id', 'context_compartments']],
]
const quote = value => "'" + value.replaceAll("'", "''") + "'"
const reference = routine => 'conv_acl_reference_' + routine

const predecessor = await readFile(new URL(source, directory), 'utf8')
if (createHash('sha256').update(predecessor).digest('hex') !== sourceDigest) {
  throw new Error('conversation_trigger_acl_source_changed')
}
const installedSuccessor = await readFile(new URL(successor, directory), 'utf8')
if (createHash('sha256').update(installedSuccessor).digest('hex') !== successorDigest) {
  throw new Error('conversation_trigger_acl_successor_changed')
}
const ordered = [...new Set([...(await readdir(directory)).filter(file => file.endsWith('.sql')), name])].sort()
const position = ordered.indexOf(name)
if (ordered[position - 1] !== source || ordered[position + 1] !== successor) {
  throw new Error('Conversation trigger ACL repair must sort after 8297 and before 8298')
}
const definitions = predecessorTriggers.map(([routine]) => {
  const prefix = `CREATE OR REPLACE FUNCTION public.${routine}()`
  const index = predecessor.indexOf(prefix)
  const end = predecessor.indexOf('$$;', index)
  if (index < 0 || end < 0 || predecessor.indexOf(prefix, index + 1) !== -1) {
    throw new Error('conversation_trigger_acl_definition_changed: ' + routine)
  }
  return `CREATE FUNCTION pg_temp.${reference(routine)}()${predecessor.slice(index + prefix.length, end + 3)}`
})
const roster = predecessorTriggers.map(([routine, trigger, type, columns]) =>
  `(${quote(routine)},${quote(reference(routine))},${quote(trigger)},${type},ARRAY[${columns.map(quote).join(',')}])`)
const functions = predecessorTriggers.map(([routine]) => 'public.' + routine + '()').join(', ')
const sql = `-- [COMP:api/migration-owner-role] Historical conversation predecessor ACL prerequisite.
-- Generated by build-conversation-trigger-legacy-acl.mjs from the immutable 8297 settings definitions.
BEGIN;
SET LOCAL search_path=pg_catalog,public,pg_temp;
${definitions.join('\n')}
DO $conversation_trigger_acl$
DECLARE
 item record; actual pg_proc; reviewed pg_proc; installed_trigger pg_trigger;
 owner_id constant oid:=(SELECT relowner FROM pg_class WHERE oid='public.sessions'::regclass);
 runtime_id constant oid:=(SELECT oid FROM pg_roles WHERE rolname='app_user');
 applied_successor constant boolean:=EXISTS(SELECT 1 FROM public._migrations WHERE name=${quote(successor)});
 grant_count integer; legacy_count integer:=0;
BEGIN
 IF NOT EXISTS(SELECT 1 FROM public._migrations WHERE name=${quote(source)})
  OR owner_id<>current_user::regrole::oid OR runtime_id IS NULL OR runtime_id=owner_id
  OR EXISTS(SELECT 1 FROM pg_event_trigger WHERE evtenabled<>'D')
  OR EXISTS(SELECT 1 FROM pg_default_acl WHERE defaclrole=owner_id AND defaclobjtype='f'
      AND defaclnamespace IN(0,'public'::regnamespace))
 THEN RAISE EXCEPTION 'conversation_trigger_acl_predecessor_changed';END IF;

 FOR item IN SELECT * FROM (VALUES
  ${roster.join(',\n  ')}
 ) AS roster(routine,reference,trigger_name,trigger_type,columns) LOOP
  SELECT * INTO STRICT reviewed FROM pg_proc
   WHERE pronamespace=pg_my_temp_schema() AND proname=item.reference AND pronargs=0;
  SELECT * INTO actual FROM pg_proc WHERE oid=to_regprocedure('public.'||item.routine||'()');
  IF actual.oid IS NULL OR actual.proowner<>owner_id
   OR (to_jsonb(actual)-ARRAY['oid','proname','pronamespace','proacl']) IS DISTINCT FROM
      (to_jsonb(reviewed)-ARRAY['oid','proname','pronamespace','proacl'])
  THEN RAISE EXCEPTION 'conversation_trigger_acl_definition_changed: %',item.routine;END IF;

  SELECT * INTO installed_trigger FROM pg_trigger WHERE tgrelid='public.sessions'::regclass AND tgname=item.trigger_name;
  IF installed_trigger.oid IS NULL OR installed_trigger.tgfoid<>actual.oid OR installed_trigger.tgtype<>item.trigger_type
   OR installed_trigger.tgenabled<>'O' OR installed_trigger.tgisinternal OR installed_trigger.tgparentid<>0
   OR installed_trigger.tgconstraint<>0 OR installed_trigger.tgdeferrable OR installed_trigger.tginitdeferred
   OR installed_trigger.tgnargs<>0 OR installed_trigger.tgqual IS NOT NULL
   OR installed_trigger.tgoldtable IS NOT NULL OR installed_trigger.tgnewtable IS NOT NULL
   OR (SELECT ARRAY(SELECT a.attname::text FROM unnest(installed_trigger.tgattr::smallint[]) WITH ORDINALITY c(attnum,position)
            JOIN pg_attribute a ON a.attrelid=installed_trigger.tgrelid AND a.attnum=c.attnum ORDER BY c.position))<>item.columns
   OR (SELECT count(*) FROM pg_depend WHERE refclassid='pg_proc'::regclass AND refobjid=actual.oid)<>1
   OR NOT EXISTS(SELECT 1 FROM pg_depend WHERE refclassid='pg_proc'::regclass AND refobjid=actual.oid AND refobjsubid=0
      AND classid='pg_trigger'::regclass AND objid=installed_trigger.oid AND objsubid=0 AND deptype='n')
  THEN RAISE EXCEPTION 'conversation_trigger_acl_binding_changed: %',item.routine;END IF;

  SELECT count(*) INTO grant_count FROM aclexplode(coalesce(actual.proacl,acldefault('f',owner_id))) a;
  IF grant_count NOT IN(2,3) OR EXISTS(
     SELECT 1 FROM aclexplode(coalesce(actual.proacl,acldefault('f',owner_id))) a
     WHERE a.grantor<>owner_id OR a.grantee NOT IN(0,owner_id,runtime_id)
        OR a.privilege_type<>'EXECUTE' OR a.is_grantable)
   OR (SELECT count(DISTINCT a.grantee) FROM aclexplode(coalesce(actual.proacl,acldefault('f',owner_id))) a
       WHERE a.grantee IN(0,owner_id))<>2
  THEN RAISE EXCEPTION 'conversation_trigger_acl_profile_changed: %',item.routine;END IF;
  IF grant_count=3 THEN legacy_count:=legacy_count+1;END IF;
 END LOOP;

 IF legacy_count=0 THEN RETURN;END IF;
 IF legacy_count<>3 OR applied_successor
 THEN RAISE EXCEPTION 'conversation_trigger_acl_unverified_historical_profile';END IF;

 REVOKE EXECUTE ON FUNCTION ${functions} FROM app_user;
 FOR item IN SELECT p.oid,p.proname,p.proacl FROM pg_proc p
  WHERE p.pronamespace='public'::regnamespace AND p.pronargs=0
   AND p.proname IN(${predecessorTriggers.map(([routine])=>quote(routine)).join(',')})
 LOOP
  IF (SELECT count(*) FROM aclexplode(coalesce(item.proacl,acldefault('f',owner_id))))<>2
   OR EXISTS(SELECT 1 FROM aclexplode(coalesce(item.proacl,acldefault('f',owner_id))) a
     WHERE a.grantor<>owner_id OR a.grantee NOT IN(0,owner_id) OR a.privilege_type<>'EXECUTE' OR a.is_grantable)
  THEN RAISE EXCEPTION 'conversation_trigger_acl_repair_changed: %',item.proname;END IF;
 END LOOP;
END $conversation_trigger_acl$;
DROP FUNCTION ${predecessorTriggers.map(([routine])=>'pg_temp.'+reference(routine)+'()').join(', ')};
${historicalOrdinaryAclSql(fileURLToPath(new URL('../../',import.meta.url)), installedSuccessor)}
COMMIT;
`

const [mode, ...extra] = process.argv.slice(2)
const destination = new URL(name, directory)
if (extra.length || (mode && mode !== '--check')) throw new Error('Use --check or no argument')
if (mode === '--check') {
  if (await readFile(destination, 'utf8') !== sql) throw new Error(name + ' needs regeneration')
  console.log(name + ' matches reviewed source')
} else {
  await writeFile(destination, sql, { flag: 'wx' })
  console.log('Generated ' + name)
}
